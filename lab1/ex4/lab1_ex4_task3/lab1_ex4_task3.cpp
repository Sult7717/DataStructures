#include <iostream>

using namespace std;

int main()
{
    int a = 5;

    // Объявление ссылки 'b', которая становится синонимом (alias) переменной 'a'
    // Знак '&' после типа данных означает инициализацию ссылки
    int& b = a;

    // Демонстрация того, что адреса переменной и ссылки полностью совпадают
    cout << "Address of a: " << &a << endl;
    cout << "Address of b: " << &b << endl;
    cout << endl;

    // Изменение значения через ссылку 'b' напрямую меняет значение в переменной 'a'
    b = 7;
    cout << "Value of a: " << a << endl;

    return 0;
}
