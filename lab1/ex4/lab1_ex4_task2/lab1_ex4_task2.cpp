#include <iostream>

using namespace std;

int main()
{
    // Инициализация статического целочисленного массива из 10 элементов
    int a[] = { 1, 2, 7, -1, 5, 3, -1, 7, 1, 6 };

    // Вывод размера типа данных int и адреса каждой ячейки массива
    // Разница между соседними адресами должна составлять ровно 4 байта
    cout << "Size of int type: " << sizeof(int) << endl;
    for (int i = 0; i < 10; i++)
    {
        cout << "Address of a[" << i << "]: " << &a[i] << endl;
    }

    cout << endl;

    // Инициализация статического массива вещественных чисел из 10 элементов
    double b[] = { 1.0, 2.0, 7.0, -1.0, 5.0, 3.5, -1.8, 7.2, 1.9, 6.2 };

    // Вывод размера типа данных double и адреса каждой ячейки массива
    // Разница между соседними адресами должна составлять ровно 8 байт
    cout << "Size of double type: " << sizeof(double) << endl;
    for (int i = 0; i < 10; i++)
    {
        cout << "Address of b[" << i << "]: " << &b[i] << endl;
    }

    return 0;
}
