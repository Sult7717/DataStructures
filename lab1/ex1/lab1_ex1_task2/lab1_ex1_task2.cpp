#include <iostream>

using namespace std;

//! \brief Накапливает сумму произведений add * i в цикле и выводит результат.
/**
* Используется для демонстрации условной точки останова: на каждой итерации
* add либо увеличивается на 10% (если i кратно 3), либо делится на 3.
*/
void Breakpoints()
{
    double add = 1.0;
    double sum = 0.0;

    for (int i = 0; i < 1000; ++i)
    {
        sum += add * i; // Поставьте условную точку останова здесь

        if (i % 3 == 0)
        {
            add *= 1.1;
        }
        else
        {
            add /= 3.0;
        }
    }

    cout << "Total sum is " << sum << endl;
}

//! \brief Точка входа в программу.
//! \return Код завершения программы (0 – успешное завершение).
int main()
{
    Breakpoints();

    return 0;
}

